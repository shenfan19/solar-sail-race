// Reference solutions for the shipped levels, one per control scheme. Not part of the game: it proves the
// levels are solvable, produces replays for the ghost, and gives verify.js something to check.
// usage: node tools/autopilot.js [levelId]    writes solutions/<level>_<scheme>.json and js/solutions.js
'use strict';
const fs = require('fs');
const path = require('path');
const Sim = require('../js/sim.js');
const Controls = require('../js/controls.js');
const levels = require('../js/levels.js');

const DEG = Math.PI / 180;

// Wanted sail normal in the light frame (n1 along e1, n2 along e2, n3 along l).
function wanted(s, opt) {
  const sa = Math.sin(opt.cone * DEG), ca = Math.cos(opt.cone * DEG);
  if (opt.law === 'spiral') return [sa, 0, ca]; // lean forward along the orbit: raises orbital energy
  // 'incline': thrust along +-h, switching sign at the nodes, which raises the inclination fastest
  const F = Sim.frame(s, {});
  const hx = s.y * s.vz - s.z * s.vy, hy = s.z * s.vx - s.x * s.vz, hz = s.x * s.vy - s.y * s.vx;
  const hn = Math.hypot(hx, hy, hz);
  const h = [hx / hn, hy / hn, hz / hn];
  let nx = -h[1], ny = h[0]; // node direction = z x h
  const nn = Math.hypot(nx, ny);
  if (nn < 1e-6) { nx = 1; ny = 0; } else { nx /= nn; ny /= nn; }
  const sign = (s.x * nx + s.y * ny) >= 0 ? 1 : -1;
  const d = [sign * h[0], sign * h[1], sign * h[2]];
  const dl = d[0] * F.lx + d[1] * F.ly + d[2] * F.lz;
  const ex = d[0] - dl * F.lx, ey = d[1] - dl * F.ly, ez = d[2] - dl * F.lz;
  const c1 = ex * F.e1x + ey * F.e1y + ez * F.e1z;
  const c2 = ex * F.e2x + ey * F.e2y + ez * F.e2z;
  const m = Math.hypot(c1, c2) || 1;
  return [sa * c1 / m, sa * c2 / m, ca];
}

function solve(level, schemeId) {
  const opt = level.autopilot, scheme = Controls.registry[schemeId], every = 10;
  const s = Sim.createState(level, schemeId);
  const keys = [];
  let cur = null;
  while (!s.done) {
    if (s.tick % every === 0) {
      const n = wanted(s, opt);
      const [a, b] = Controls.clamp(scheme, ...scheme.fromLocal(n[0], n[1], n[2]));
      if (!cur || cur.a !== a || cur.b !== b) { cur = { t: s.tick, a: a, b: b }; keys.push(cur); }
    }
    Sim.step(s, cur.a, cur.b);
  }
  return { keys, status: s.done, ticks: s.tick };
}

if (require.main === module) {
  const want = process.argv[2];
  const out = path.join(__dirname, '..', 'solutions');
  fs.mkdirSync(out, { recursive: true });
  const all = {};
  for (const lv of levels) {
    if (want && lv.id !== want) continue;
    all[lv.id] = {};
    for (const id of Controls.order) {
      const r = solve(lv, id);
      const check = Sim.runReplay(lv, r.keys, id);
      console.log(lv.id, id, r.status, 'time', (r.ticks * lv.dt).toFixed(1), lv.timeScaleLabel, 'keys', r.keys.length,
        'replay', check.status, check.ticks === r.ticks ? 'same' : 'DIFFERENT');
      if (r.status === 'success' && check.ticks === r.ticks) {
        fs.writeFileSync(path.join(out, lv.id + '_' + id + '.json'),
          JSON.stringify({ v: 2, level: lv.id, control: id, keys: r.keys }));
        all[lv.id][id] = { ticks: check.ticks, keys: r.keys };
      }
    }
  }
  if (!want) fs.writeFileSync(path.join(__dirname, '..', 'js', 'solutions.js'),
    '// Generated by tools/autopilot.js. Reference solutions used as ghosts.\n' +
    'window.SailSolutions = ' + JSON.stringify(all) + ';\n');
}
module.exports = { solve };
